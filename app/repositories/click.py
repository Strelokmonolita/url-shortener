"""Append-only persistence of pseudonymous redirect events."""

from __future__ import annotations

from sqlalchemy.exc import IntegrityError
from sqlalchemy.ext.asyncio import AsyncSession

from app.models import Click


class ClickRepository:
    """Persist visitor hashes and bounded request metadata, never raw IP addresses."""

    def __init__(self, session: AsyncSession) -> None:
        self._session = session

    async def create(
        self,
        *,
        link_id: int,
        visitor_hash: str | None,
        user_agent: str | None,
        referer: str | None,
    ) -> Click:
        """Commit one click; its timestamp is generated by the database."""
        click = Click(
            link_id=link_id,
            visitor_hash=visitor_hash,
            user_agent=user_agent,
            referer=referer,
        )
        self._session.add(click)
        try:
            await self._session.commit()
        except IntegrityError:
            await self._session.rollback()
            raise
        return click
